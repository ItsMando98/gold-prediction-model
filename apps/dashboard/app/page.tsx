import { DriverBars } from "@/components/DriverBars";
import { RiskGauge } from "@/components/RiskGauge";
import { RiskHistoryChart } from "@/components/RiskHistoryChart";
import { StatTile } from "@/components/StatTile";
import { StatusList } from "@/components/StatusList";
import { getCurrentPrediction, getPredictionHistory } from "@/lib/api";
import { formatDate, titleCase } from "@/lib/format";

export default async function OverviewPage() {
  const [prediction, history] = await Promise.all([
    getCurrentPrediction(),
    getPredictionHistory(),
  ]);

  if (!prediction) {
    return (
      <div className="card empty-state">
        <svg className="icon" width="40" height="40" viewBox="0 0 24 24" fill="none" aria-hidden="true">
          <circle cx="12" cy="12" r="9" stroke="currentColor" strokeWidth="1.5" />
          <path d="M12 8v5M12 16h.01" stroke="currentColor" strokeWidth="1.5" strokeLinecap="round" />
        </svg>
        <p>No prediction available yet.</p>
        <p className="muted">
          Run the worker&apos;s weekly job (<code>python -m apps.worker.jobs</code>, or the Agent
          Team via <code>run_weekly_pipeline</code>) once historical data has been backfilled.
        </p>
      </div>
    );
  }

  const isCalibrated = prediction.model_versions?.calibrated === true;

  return (
    <>
      <div className="card hero-card">
        <RiskGauge score={prediction.risk_score} bias={prediction.bias} />
        <div className="meta-row">
          <span>
            Regime: <strong>{titleCase(prediction.regime)}</strong>
          </span>
          <span>&middot;</span>
          <span>
            Confidence: <strong>{(prediction.confidence * 100).toFixed(0)}%</strong>{" "}
            {!isCalibrated && <span title="Not yet backed by a historical calibration run">(uncalibrated)</span>}
          </span>
          <span>&middot;</span>
          <span>
            {titleCase(prediction.horizon)} &rarr; {formatDate(prediction.target_time)}
          </span>
        </div>
      </div>

      <div className="grid grid-stats" style={{ marginBottom: "1.25rem" }}>
        <StatTile label="Confidence" value={`${(prediction.confidence * 100).toFixed(0)}%`} meterPct={prediction.confidence * 100} />
        <StatTile label="Regime" value={titleCase(prediction.regime)} />
        <StatTile
          label="ML model"
          value={prediction.ml_score !== null ? `${(prediction.ml_score * 100).toFixed(0)}% P(down)` : "Inactive"}
          hint={prediction.ml_score !== null ? "blended into risk score" : "deterministic score only"}
        />
        <StatTile label="Target" value={formatDate(prediction.target_time).split(",")[0]} hint={prediction.horizon.replace(/_/g, " ")} />
      </div>

      {prediction.narrative && (
        <div className="card">
          <h2>Explanation</h2>
          <p style={{ margin: 0, lineHeight: 1.55 }}>{prediction.narrative}</p>
          <p className="muted" style={{ fontSize: "0.72rem", marginTop: "0.75rem", marginBottom: 0 }}>
            Generated by the Explanation Agent &mdash; describes the score, never sets it.
          </p>
        </div>
      )}

      {history && history.length > 1 && (
        <div className="card">
          <h2>Risk score trend</h2>
          <RiskHistoryChart history={history} />
        </div>
      )}

      <DriverBars drivers={prediction.drivers} />

      <div className="grid two-col">
        <div className="card">
          <h2>Key levels</h2>
          <ul className="level-list">
            <li className="level-row">
              <span className="muted">Resistance</span>
              <span className="value">{prediction.key_levels.resistance?.join(", ") ?? "—"}</span>
            </li>
            <li className="level-row">
              <span className="muted">Support</span>
              <span className="value">{prediction.key_levels.support?.join(", ") ?? "—"}</span>
            </li>
          </ul>
        </div>

        <div className="card">
          <h2>Confirmation</h2>
          <StatusList items={prediction.confirmations} kind="confirmation" />
        </div>
      </div>

      <div className="card">
        <h2>Invalidation</h2>
        <StatusList items={prediction.invalidation} kind="invalidation" />
      </div>

      {prediction.contradictions.length > 0 && (
        <div className="card">
          <h2>Contradicting signals</h2>
          <ul className="status-list">
            {prediction.contradictions.map((c) => (
              <li className="status-item" key={c}>
                <span>{c}</span>
              </li>
            ))}
          </ul>
        </div>
      )}

      <p className="footer-note">
        Probabilities remain uncalibrated until a walk-forward backtest validates them &mdash; see{" "}
        docs/ROADMAP.md in the repository.
      </p>
    </>
  );
}
